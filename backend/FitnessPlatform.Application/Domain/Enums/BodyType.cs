namespace FitnessPlatform.Application.Domain.Enums;

/// <summary>
/// Somatotype / body constitution classification.
/// </summary>
public enum BodyType
{
    /// <summary>
    /// Lean build, fast metabolism, difficulty gaining mass.
    /// </summary>
    Ectomorph,

    /// <summary>
    /// Athletic build, responds well to both muscle gain and fat loss.
    /// </summary>
    Mesomorph,

    /// <summary>
    /// Broader build, tends to store fat more easily.
    /// </summary>
    Endomorph
}
