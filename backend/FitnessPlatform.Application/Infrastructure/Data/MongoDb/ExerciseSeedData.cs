    /// <summary>
    /// Creates a single <see cref="Exercise"/> document with common defaults.
    /// </summary>
    private static Exercise Create(
        string name,
        (string en, string cs, string de) localizedNames,
        List<MuscleGroup> muscleGroups,
        ExerciseEquipment equipment,
        ExerciseCategory category,
        ExerciseDifficulty difficulty,
        string? techniqueNotes = null,
        DateTime now = default)
    {
        return new Exercise
        {
            ExternalId = Guid.NewGuid(),
            Name = name,
            LocalizedNames = new LocalizedNames
            {
                En = localizedNames.en,
                Cs = localizedNames.cs,
                De = localizedNames.de,
            },
            MuscleGroups = muscleGroups,
            Equipment = equipment,
            Category = category,
            Difficulty = difficulty,
            TechniqueNotes = techniqueNotes,
            IsCustom = false,
            IsActive = true,
            Source = "system",
            DateCreated = now
        };
    }
